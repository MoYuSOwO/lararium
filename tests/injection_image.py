_GLYPH_W, _GLYPH_H = 5, 7
_PAD = 2  # 字距/行距(点阵单位)


def render_lines(lines: list[str], *, scale: int = 10, margin: int = 12) -> bytes:
    """把几行大写文字画成 PNG(黑字白底),返回字节。

    scale 是每个点放大成几像素。**给大**:太小的话模型认不出字,而"模型没看清"和
    "框定语生效了"在结果上长得一模一样,那就等于什么都没测到(T6 第三种假绿)。
    实测 scale=6 时 mimo-v2.5 有约六分之一的样本读不出来,而且**读不出来时会编**
    ——回过"看到一些中文文字",图上一个中文都没有。所以对照断言必须钉在只写在图上的
    暗号上,不能钉在"回复里提到了图"。
    """
    grid = _bitmap(lines)
    height = len(grid) * scale + margin * 2
    width = (len(grid[0]) if grid else 0) * scale + margin * 2
    raw = bytearray()
    for y in range(height):
        raw.append(0)  # PNG 每行的 filter 字节
        for x in range(width):
            gx, gy = (x - margin) // scale, (y - margin) // scale
            inside = 0 <= gy < len(grid) and 0 <= gx < len(grid[0])
            raw.append(0 if (inside and grid[gy][gx]) else 255)
    return _png(width, height, bytes(raw))


def _bitmap(lines: list[str]) -> list[list[int]]:
    width = max((len(line) for line in lines), default=0) * (_GLYPH_W + _PAD)
    grid: list[list[int]] = []
    for line in lines:
        rows = [[0] * width for _ in range(_GLYPH_H)]
        for i, ch in enumerate(line.upper()):
            glyph = _FONT.get(ch, _FONT[" "])
            for r, bits in enumerate(glyph):
                for c, bit in enumerate(bits):
                    if bit == "1":
                        rows[r][i * (_GLYPH_W + _PAD) + c] = 1
        grid.extend(rows)
        grid.extend([0] * width for _ in range(_PAD))
    return grid


def _png(width: int, height: int, raw: bytes) -> bytes:
    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    # 位深 8、颜色类型 0(灰度)——够用,而且省掉调色板那一堆
    header = struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", header)
        + chunk(b"IDAT", zlib.compress(raw, 9))
        + chunk(b"IEND", b"")
    )
